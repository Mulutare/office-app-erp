        ON DELETE CASCADE,
    CONSTRAINT fk_attendance_push_delivery_sub
        FOREIGN KEY (subscription_id)
        REFERENCES attendance_push_subscriptions(subscription_id)
        ON DELETE CASCADE
)
SQL,
