CREATE TABLE attendance_push_deliveries (
    notification_id NUMBER(19) NOT NULL,
    subscription_id NUMBER(19) NOT NULL,
    delivery_status VARCHAR2(20 CHAR)
        DEFAULT 'pending' NOT NULL,
    attempts NUMBER(5) DEFAULT 0 NOT NULL,
    next_attempt_at TIMESTAMP(6),
    last_status_code NUMBER(5),
    failure_reason VARCHAR2(500 CHAR),
    delivered_at TIMESTAMP(6),
    created_at TIMESTAMP(6)
        DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6)
        DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_attendance_push_delivery
        PRIMARY KEY (
            notification_id,
            subscription_id
        ),
    CONSTRAINT ck_attendance_push_delivery_status
        CHECK (
            delivery_status IN (
                'pending',
                'delivered',
                'retry',
                'failed'
            )
        ),
    CONSTRAINT fk_attendance_push_delivery_notice
        FOREIGN KEY (notification_id)
